export const getColumn = (slug: string) => columns.find((c) => c.slug === slug);

export const columnsByDate = [...columns].sort((a, b) => (a.date < b.date ? 1 : -1));

export const columnsInCategory = (name: ColumnCategory) =>
  columnsByDate.filter((c) => c.category === name);

export const countInCategory = (name: ColumnCategory) =>
  columns.filter((c) => c.category === name).length;

/** 公開日の新しい順に並べたときの前後。記事下のページ送りに使う。 */
export function siblings(slug: string) {
  const i = columnsByDate.findIndex((c) => c.slug === slug);
  return {
    newer: i > 0 ? columnsByDate[i - 1] : undefined,
    older: i >= 0 && i < columnsByDate.length - 1 ? columnsByDate[i + 1] : undefined,
  };
}

export const blockText = (b: Block) => (b.type === "list" ? b.items.join("") : b.text);

export const plainText = (col: Column) => col.body.map(blockText).join("");

export function readingMinutes(col: Column) {
  return Math.max(1, Math.round(plainText(col).length / 500));
}

/** 目次に出す見出し。id は本文側の見出しと対応させる。 */
export function headings(col: Column) {
  const out: { id: string; text: string }[] = [];
  let n = 0;
  for (const b of col.body) {
    if (b.type !== "h2") continue;
    n += 1;
    out.push({ id: `sec-${n}`, text: b.text });
  }
  return out;
}

export const formatDate = (iso: string) =>
  new Date(`${iso}T00:00:00+09:00`).toLocaleDateString("ja-JP", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
